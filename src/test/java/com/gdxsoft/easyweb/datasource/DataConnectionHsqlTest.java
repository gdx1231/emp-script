	private static final String CFG = "hsql_dc_test";
	private static RequestValue baseRv;

	@BeforeAll
	static void initDatasource() throws Exception {
		ConnectionConfig cfg = new ConnectionConfig();
		cfg.setName(CFG);
		cfg.setType("HSQLDB");
		cfg.setConnectionString(CFG);
		cfg.setSchemaName("PUBLIC");

		MTableStr pool = new MTableStr();
		pool.put("driverClassName", "org.hsqldb.jdbc.JDBCDriver");
		pool.put("url", "jdbc:hsqldb:mem:dc_test;shutdown=true");
		pool.put("username", "SA");
		pool.put("password", "");
		pool.put("maxActive", "5");
		cfg.setPool(pool);

		ConnectionConfigs.instance().put(CFG, cfg);

		// Base RequestValue with common params
		baseRv = new RequestValue();
		baseRv.addValue("NAME", "alice", PageValueTag.FORM);
		baseRv.addValue("AGE", "30", PageValueTag.FORM);
		baseRv.getPageValues().getValue("AGE").setDataType("INT");
		baseRv.addValue("SCORE", "95.5", PageValueTag.FORM);
		baseRv.getPageValues().getValue("SCORE").setDataType("NUMBER");

		// Create schema
		DataConnection c = new DataConnection(CFG, null);
		c.executeUpdateNoParameter("DROP TABLE IF EXISTS dc_user");
		c.executeUpdateNoParameter(
				"CREATE TABLE dc_user ("
				+ "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
				+ "name VARCHAR(200) NOT NULL, "
				+ "age INTEGER, "
				+ "score DECIMAL(10,2), "
				+ "active BOOLEAN DEFAULT TRUE, "
				+ "memo LONGVARCHAR, "
				+ "created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP"
				+ ")");
		c.close();
	}

	@BeforeEach
	void cleanTable() {
		DataConnection c = new DataConnection(CFG, null);
		c.executeUpdateNoParameter("DELETE FROM dc_user");
		c.close();
	}

	private DataConnection createConn() {
		return new DataConnection(CFG, baseRv);
	}

	private DataConnection createConn(RequestValue rv) {
		return new DataConnection(CFG, rv);
	}

	private DataConnection createConnNoRv() {
		return new DataConnection(CFG, null);
	}

