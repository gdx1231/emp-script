	// ═══════════════════════════════════════════════════════════════
	//  5. Transaction
	// ═══════════════════════════════════════════════════════════════

	@Test
	@Order(40)
	void testTransactionCommit() {
		DataConnection c = createConnNoRv();
		assertTrue(c.transBegin());

		c.executeUpdateNoParameter("INSERT INTO dc_user (name, age) VALUES ('tx1', 1)");
		c.executeUpdateNoParameter("INSERT INTO dc_user (name, age) VALUES ('tx2', 2)");

		assertTrue(c.transCommit());

		DTTable tb = DTTable.getJdbcTable("SELECT COUNT(*) FROM dc_user", c);
		assertEquals(2, tb.getCell(0, 0).toInt());
		c.close();
	}

	@Test
	@Order(41)
	void testTransactionRollback() {
		DataConnection c = createConnNoRv();
		// Seed one row outside transaction
		c.executeUpdateNoParameter("INSERT INTO dc_user (name, age) VALUES ('pre_tx', 0)");

		assertTrue(c.transBegin());
		c.executeUpdateNoParameter("INSERT INTO dc_user (name, age) VALUES ('tx_rollback', 99)");
		c.transRollback();
		// transRollback calls close(), need new connection to verify
		// Already closed by transRollback

		DataConnection c2 = createConnNoRv();
		DTTable tb = DTTable.getJdbcTable("SELECT COUNT(*) FROM dc_user", c2);
		assertEquals(1, tb.getCell(0, 0).toInt(), "Rollback should revert the second insert");
		c2.close();
	}

	@Test
	@Order(42)
	void testIsTrans() {
		DataConnection c = createConnNoRv();
		assertFalse(c.isTrans());
		c.transBegin();
		assertTrue(c.isTrans());
		c.transCommit();
		assertFalse(c.isTrans());
		c.close();
	}

